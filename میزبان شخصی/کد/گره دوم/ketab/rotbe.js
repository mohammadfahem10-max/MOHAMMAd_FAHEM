class Kesh {
  constructor(ms, max){ this.ms = ms || 600000; this.max = max || 200; this.m = new Map(); }
  get(k){ const x = this.m.get(k); if (!x) return undefined; if (Date.now() - x.t > this.ms){ this.m.delete(k); return undefined; } return x.v; }
  set(k, v){ this.m.set(k, { v, t: Date.now() }); if (this.m.size > this.max) this.m.delete(this.m.keys().next().value); return v; }
  get size(){ return this.m.size; }
}
