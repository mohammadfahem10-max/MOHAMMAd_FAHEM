function yeksan(s){
  return String(s || '').replace(/[يى]/g, 'ی').replace(/ك/g, 'ک').replace(/[ۀة]/g, 'ه').replace(/[أإآ]/g, 'ا').replace(/ؤ/g, 'و').replace(/ئ/g, 'ی')
    .replace(/[ً-ٰٟـ]/g, '').replace(/آئین/g, 'آیین').replace(/[۰-۹]/g, c => '0123456789'['۰۱۲۳۴۵۶۷۸۹'.indexOf(c)])
    .replace(/[‌‍‎‏]/g, ' ').replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
}
function kelidNam(s){ return yeksan(s).replace(/ /g, ''); }

