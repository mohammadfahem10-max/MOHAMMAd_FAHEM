const MADAR = QANUN_MADAR.map(n => ({ k: kelidNam(n), s: ' ' + yeksan(n) + ' ' }));
const ESLAHI = /^(قانون |لایحه قانونی )?(اصلاحیه|اصلاح|الحاق|تمدید|تفسیر|متمم|نسخ|ایین ?نامه اجرایی)/;
/* عنوان یک قانون مادر است؟ 2: خود قانون · 1: اصلاحیه/آیین‌نامهٔ اجرایی/وابستهٔ آن · 0: نه */
function madarAst(onvan){
  const y = yeksan(onvan), k = y.replace(/ /g, ''), ys = ' ' + y + ' ';
  const eslahi = ESLAHI.test(y);
  for (const m of MADAR){
    if (k.startsWith(m.k)){
      const rest = k.slice(m.k.length);
      if (!eslahi && (rest === '' || /^(مصوب|\d|با|ایران|جمهوری)/.test(rest))) return 2;
    }
    if (ys.includes(m.s) || (m.k.length > 14 && k.includes(m.k))) return (!eslahi && k.startsWith(m.k)) ? 2 : 1;
  }
  return 0;
}
/* مصوبه‌های بودجه‌ای و موافقت‌های موردی (نویز پرسش‌های عمومی) */
const MOVARDI = /(موافقت|بودجه|اعتبار|تخصیص|کمک|واگذاری|اساسنامه|موافقتنامه|کنوانسیون|پروتکل|یادداشت تفاهم|تفاهم نامه|اتحادیه|پستی|عضویت|الحاق دولت|جدول|ردیف|تعرفه|سهمیه|انتصاب|تعیین نماینده|استرداد مجرمین|معاضدت قضایی|دولت جمهوری)/;
function movardiAst(onvan, lar){
  const y = yeksan(onvan);
  if (lar === 'lar8' && !/^(آیین نامه اجرایی قانون|ایین نامه اجرایی قانون)/.test(y)) return MOVARDI.test(y) ? 2 : 1;
  return MOVARDI.test(y) && !madarAst(onvan) ? 1 : 0;
}
const ZARIB = { madar: 0.025, madarFar: 0.008, hadaf: 0.02, movardi: -0.015, movardiKam: -0.006 };
/* امتیاز افزودنی به RRF: pors = متن پرسش (خام یا بازنویسی)، qids = قانون‌هایی که پرسش یا بازنویسی نام برده */
function zarib(r, pors, qidsHadaf){
  let z = 0; const m = madarAst(r.onvan);
  if (m === 2) z += ZARIB.madar; else if (m === 1) z += ZARIB.madarFar;
  if (qidsHadaf && qidsHadaf.has && qidsHadaf.has(r.qid)) z += ZARIB.hadaf;
  const mv = movardiAst(r.onvan, r.lar);
  if (mv){
    const p = yeksan(pors); const mm = yeksan(r.onvan).match(MOVARDI);
    const soriah = /هیئت وزیران|هیات وزیران|مصوبه|تصویب ?نامه|بودجه|موافقت ?نامه|کنوانسیون|پستی/.test(p) || !!(mm && p.includes(mm[0]));
    if (!soriah) z += mv === 2 ? ZARIB.movardi : ZARIB.movardiKam;
  }
  return z;
}

/* پرسش FTS5 از بازنویسی: عبارت‌های حقوقی به صورت عبارت ("چک برگشتی") و واژه‌ها؛ واژه‌های بی‌ارزش بیرون */
const IST_MOHAVERE = new Set(('اگه اگر یکی یه یک چیکار چکار چی چیه چیست چه باید بکنم کنم بکنیم کنیم میشه میشود چطوری چطور چگونه من منو مرا ما تو شما اون او این اینو اونو که را رو و یا با به از در برای برام تا هم هنوز الان حالا خب خوب لطفا میخوام میخواهم دارم داره داریم هست است نیست بود شده شد میکنه کرده کرد کنه بکن بگو بنویس بیار بیاور بده توضیح ساده کامل دیگه ولی اما چون وقتی آیا یعنی بعد قبل پس کی کجا کدوم کدام چند چقدر چرا همه همون همین باشه باشد بشه میتونم ازش بهش باهاش براش طرف خیلی زیاد چیزی کاری می های ها ی ای شود گردد نماید').split(' '));
function sazandeFts(o, norm, istFts){
  o = o || {}; norm = norm || yeksan;
  const bad = w => !w || w.length < 2 || IST_MOHAVERE.has(w) || (istFts && istFts.has(w)) || /^\d+$/.test(w) && w.length < 2;
  const out = [], seen = new Set();
  const add = x => { if (!x || seen.has(x)) return; seen.add(x); out.push(x); };
  for (const e of (o.ebarat || [])){
    const w = norm(e).split(/[^\p{L}\p{N}]+/u).filter(x => x && !(IST_MOHAVERE.has(x) && x.length < 3));
    if (!w.length) continue;
    if (w.length === 1){ if (!bad(w[0])) add('"' + w[0] + '"'); }
    else add('"' + w.join(' ') + '"');
  }
  for (const v of (o.vazheha || [])) for (const w of norm(v).split(/[^\p{L}\p{N}]+/u)) if (!bad(w) && w.length > 2) add('"' + w + '"');
  return out.slice(0, 16).join(' OR ');
}

